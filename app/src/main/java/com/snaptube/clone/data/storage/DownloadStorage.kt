package com.snaptube.clone.data.storage

import android.content.Context
import android.content.Intent
import android.net.Uri
import androidx.documentfile.provider.DocumentFile
import com.snaptube.clone.data.model.StorageEntry
import com.snaptube.clone.data.prefs.AppPreferences
import java.io.File
import java.io.IOException

/**
 * Real Storage Access Framework support for user-chosen download folders.
 *
 * Downloads are first written to app-private storage (fast, resumable), then
 * copied into the persisted SAF tree so they survive uninstalling the app.
 */
object DownloadStorage {

    private const val MIME_FALLBACK = "application/octet-stream"

    fun isEnabled(): Boolean = AppPreferences.downloadTreeUri.isNotBlank()

    fun treeUri(): Uri? = AppPreferences.downloadTreeUri
        .takeIf { it.isNotBlank() }
        ?.let { runCatching { Uri.parse(it) }.getOrNull() }

    fun root(context: Context): DocumentFile? {
        val uri = treeUri() ?: return null
        return runCatching { DocumentFile.fromTreeUri(context, uri) }.getOrNull()
    }

    fun persist(context: Context, uri: Uri) {
        val flags = Intent.FLAG_GRANT_READ_URI_PERMISSION or
            Intent.FLAG_GRANT_WRITE_URI_PERMISSION
        runCatching {
            context.contentResolver.takePersistableUriPermission(uri, flags)
        }
        AppPreferences.downloadTreeUri = uri.toString()
    }

    fun clear() {
        AppPreferences.downloadTreeUri = ""
    }

    /** Friendly name shown in Settings, e.g. "Download" or the tree's last segment. */
    fun displayName(context: Context): String {
        if (!isEnabled()) return ""
        val root = root(context) ?: return AppPreferences.downloadTreeUri
        return root.name ?: (AppPreferences.downloadTreeUri.substringAfterLast('/'))
    }

    /**
     * Copies [source] into the selected tree, using a unique display name.
     * Returns the new `content://` URI, or null when no tree is configured.
     */
    fun copyToTree(
        context: Context,
        source: File,
        displayName: String,
        mimeType: String
    ): Uri? {
        if (!isEnabled()) return null
        val root = root(context)
            ?: throw IOException("Download folder is no longer accessible")
        if (!root.canWrite()) throw IOException("Download folder is read-only")
        if (source.length() <= 0L) throw IOException("Source file is empty")

        val safeName = sanitizeName(displayName).ifBlank { "SnapTube" }
        val target = createUniqueFile(root, mimeType, safeName)
            ?: throw IOException("Could not create a file in the download folder")

        try {
            context.contentResolver.openOutputStream(target.uri, "w").use { output ->
                if (output == null) throw IOException("Could not open the target file")
                source.inputStream().use { input -> input.copyTo(output, 128 * 1024) }
                output.flush()
            }
            if (target.length() <= 0L) throw IOException("Copied file is empty")
            return target.uri
        } catch (t: Throwable) {
            runCatching { target.delete() }
            throw t
        }
    }

    /** Saves generated bytes (MP3 / backup) straight into the tree. */
    fun writeToTree(
        context: Context,
        displayName: String,
        mimeType: String,
        write: (java.io.OutputStream) -> Unit
    ): Uri? {
        if (!isEnabled()) return null
        val root = root(context) ?: return null
        val target = createUniqueFile(root, mimeType, sanitizeName(displayName))
            ?: return null
        try {
            context.contentResolver.openOutputStream(target.uri, "w").use { output ->
                if (output == null) throw IOException("Could not open the target file")
                write(output)
                output.flush()
            }
            return target.uri
        } catch (t: Throwable) {
            runCatching { target.delete() }
            throw t
        }
    }

    fun listMedia(context: Context): List<StorageEntry> {
        val root = root(context) ?: return emptyList()
        return runCatching {
            root.listFiles()
                .filter { it.isFile }
                .mapNotNull { file ->
                    val name = file.name ?: return@mapNotNull null
                    StorageEntry(
                        uri = file.uri.toString(),
                        name = name,
                        sizeBytes = file.length(),
                        lastModified = file.lastModified(),
                        mimeType = file.type ?: mimeForName(name)
                    )
                }
        }.getOrDefault(emptyList())
    }

    fun delete(context: Context, uriString: String): Boolean {
        if (!uriString.startsWith("content://")) return false
        return runCatching {
            val uri = Uri.parse(uriString)
            DocumentFile.fromSingleUri(context, uri)?.delete()
                ?: (context.contentResolver.delete(uri, null, null) > 0)
        }.getOrDefault(false)
    }

    fun sizeOf(context: Context, uriString: String): Long {
        if (!uriString.startsWith("content://")) {
            return runCatching { File(uriString).length() }.getOrDefault(0L)
        }
        return runCatching {
            DocumentFile.fromSingleUri(context, Uri.parse(uriString))?.length() ?: 0L
        }.getOrDefault(0L)
    }

    fun nameOf(context: Context, uriString: String): String {
        if (!uriString.startsWith("content://")) {
            return runCatching { File(uriString).name }.getOrDefault(uriString)
        }
        return runCatching {
            DocumentFile.fromSingleUri(context, Uri.parse(uriString))?.name
        }.getOrNull() ?: uriString.substringAfterLast('/')
    }

    fun mimeForName(name: String): String = when (name.substringAfterLast('.', "").lowercase()) {
        "mp4", "m4v", "mov" -> "video/mp4"
        "webm" -> "video/webm"
        "mkv" -> "video/x-matroska"
        "3gp" -> "video/3gpp"
        "m4a", "aac" -> "audio/mp4"
        "mp3" -> "audio/mpeg"
        "opus", "ogg" -> "audio/ogg"
        "wav" -> "audio/wav"
        "flac" -> "audio/flac"
        "srt" -> "application/x-subrip"
        "vtt" -> "text/vtt"
        "json" -> "application/json"
        else -> MIME_FALLBACK
    }

    private fun createUniqueFile(root: DocumentFile, mimeType: String, name: String): DocumentFile? {
        val base = name.substringBeforeLast('.', name)
        val extension = name.substringAfterLast('.', "")
        val existing = root.listFiles().mapNotNull { it.name }.toSet()
        var candidate = name
        var index = 2
        while (candidate in existing) {
            candidate = if (extension.isBlank()) "$base ($index)" else "$base ($index).$extension"
            index++
        }
        return root.createFile(mimeType, candidate)
            ?: root.createFile(MIME_FALLBACK, candidate)
    }

    private fun sanitizeName(name: String): String =
        name.replace(Regex("[\\\\/:*?\"<>|\\n\\r\\u0000]"), "_").trim().take(120)

    fun isContentUri(path: String): Boolean = path.startsWith("content://")
}
